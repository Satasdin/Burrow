#!/usr/bin/env python3
"""Writes Sources/BurrowTools/ConnectPlugins.swift from the gate plugins in integrations/ (D-108), so `burrow connect`
installs exactly the files the repository ships. Run it after changing anything in integrations/*/burrow-gate/;
ConnectTests fails until the two agree."""
import os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
FILES = [
    ("openCode", "integrations/opencode/burrow-gate/index.js"),
    ("openClaw", "integrations/openclaw/burrow-gate/index.mjs"),
    ("openClawManifest", "integrations/openclaw/burrow-gate/openclaw.plugin.json"),
    ("openClawPackage", "integrations/openclaw/burrow-gate/package.json"),
    ("hermes", "integrations/hermes/burrow-gate/__init__.py"),
    ("hermesManifest", "integrations/hermes/burrow-gate/plugin.yaml"),
]

out = ["// Generated by scripts/embed-integrations.py from integrations/*/burrow-gate. Do not edit by hand.",
       "", "/// The gate plugins `burrow connect` installs, byte for byte the files in integrations/ (D-108).",
       "public enum ConnectPlugins {",
       "    /// Each embedded file and where it lives in the repository, for the test that keeps them the same.",
       "    public static let sources: [(name: String, path: String, text: String)] = ["]
out += [f'        ("{name}", "{path}", {name}),' for name, path in FILES]
out.append("    ]")
for name, path in FILES:
    text = open(os.path.join(ROOT, path), encoding="utf-8").read()
    assert '"""####' not in text
    body = text.split("\n")[:-1] if text.endswith("\n") else text.split("\n")
    out += ["", f"    /// {path}", f'    public static let {name} = ####"""', *body,
            '    """####' + (' + "\\n"' if text.endswith("\n") else "")]
out.append("}")
# Swift's multi-line literal strips the closing delimiter's indentation from every line, so the body is indented too.
lines, body = [], False
for line in out:
    if line.endswith('= ####"""'):
        lines.append(line); body = True; continue
    if body and line.startswith('    """####'):
        lines.append(line); body = False; continue
    lines.append(("    " + line) if body and line else line)
open(os.path.join(ROOT, "Sources/BurrowTools/ConnectPlugins.swift"), "w", encoding="utf-8").write("\n".join(lines) + "\n")
print("wrote Sources/BurrowTools/ConnectPlugins.swift")
